"""Build the flat Qollab upload from the canonical Python package and web files."""
import argparse
import json
from pathlib import Path
import zipfile

ROOT = Path(__file__).resolve().parent
MODULES = ('__init__', 'i18n', 'gates', 'classic', 'quantum', 'remote', 'game', 'tutorial', 'service')


def engine_source():
    sources = {name: (ROOT / 'truco' / f'{name}.py').read_text() for name in MODULES}
    payload = repr(json.dumps(sources, ensure_ascii=True, separators=(',', ':')))
    return '''"""Generated by build_qollab.py. Edit truco/*.py, then rebuild this file.

Qollab receives this single Python file at project root, without folder uploads.
The original MIT game modules run unchanged in a private in-memory package.
"""
import json
import sys
import types
# Explicit imports also expose these dependencies to Python runtime loaders.
import qiskit
import numpy

_SOURCES = json.loads(''' + payload + ''')
_SERVICE = None


def _service():
    global _SERVICE
    if _SERVICE is None:
        root = '_qriollo_qollab'
        package = types.ModuleType(root)
        package.__path__ = []
        package.__package__ = root
        sys.modules[root] = package
        exec(compile(_SOURCES['__init__'], '<qollab_engine/__init__.py>', 'exec'), package.__dict__)
        for name in ('i18n', 'gates', 'classic', 'quantum', 'remote', 'game', 'tutorial', 'service'):
            module = types.ModuleType(root + '.' + name)
            module.__package__ = root
            module.__file__ = '<qollab_engine/' + name + '.py>'
            sys.modules[module.__name__] = module
            setattr(package, name, module)
            exec(compile(_SOURCES[name], module.__file__, 'exec'), module.__dict__)
        _SERVICE = sys.modules[root + '.service']
    return _SERVICE


def dispatch_json(payload):
    return _service().dispatch_json(payload)


def start_json(backend):
    return _service().start_json(backend)


def poll_json():
    return _service().poll_json()


def demo_json():
    return _service().demo_json()
'''


def upload_files():
    files = [*sorted(ROOT.glob('*.js')), ROOT / 'main.css', ROOT / 'index.html',
             ROOT / 'qollab_engine.py', ROOT / 'requirements.txt', ROOT / 'README.md', ROOT / 'LICENSE',
             ROOT / 'QOLLAB_UPDATE.md', ROOT / 'THIRD_PARTY_NOTICES.md', ROOT / 'DEMO_SCRIPT.md',
             ROOT / 'artifacts' / 'truco-cuantico-demo.mp4',
             ROOT / 'artifacts' / 'DEMO_TRANSCRIPT.txt']
    # The HTTP bridge is only for local development, never part of Qollab.
    return [file for file in files if file.name != 'local-engine.js']


def build(output=None, check=False, verify_zip=None):
    source = engine_source()
    engine = ROOT / 'qollab_engine.py'
    if check:
        if not engine.is_file() or engine.read_text() != source:
            raise SystemExit('qollab_engine.py is stale; run python build_qollab.py')
    else:
        engine.write_text(source)
    if output:
        output = Path(output)
        output.parent.mkdir(parents=True, exist_ok=True)
        files = upload_files()
        with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as archive:
            for file in files:
                archive.write(file, file.name)
        print(f'Flat Qollab upload: {output} ({len(files)} root files)')
    if verify_zip:
        with zipfile.ZipFile(verify_zip) as archive:
            files=upload_files()
            if sorted(archive.namelist()) != sorted(file.name for file in files):
                raise SystemExit('Qollab ZIP has missing, extra or duplicate files; rebuild it')
            for file in files:
                if archive.read(file.name) != file.read_bytes():
                    raise SystemExit(f'Qollab ZIP is stale: {file.name}; rebuild it')
        print(f'Verified Qollab ZIP: {verify_zip}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--zip', help='Optional flat upload ZIP destination')
    parser.add_argument('--verify-zip', help='Verify an existing upload matches current files')
    options = parser.parse_args()
    build(options.zip, options.check, options.verify_zip)
